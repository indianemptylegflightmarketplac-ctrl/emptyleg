-- ---------------------------------------------------------------------
-- 1. Operator listing submissions (pending approval)
-- ---------------------------------------------------------------------
create table if not exists public.operator_listing_submissions (
  id              bigint generated by default as identity primary key,
  -- Operator details
  operator_name          text        not null,
  operator_email         text        not null,
  operator_phone         text        not null,
  operator_company       text,
  operator_city          text,
  -- Aircraft details
  aircraft_type          text        not null,
  aircraft_category      text        not null
    check (aircraft_category in ('Light', 'Midsize', 'Heavy', 'Turboprop', 'Ultra-Long Range')),
  passenger_capacity     integer     not null
    check (passenger_capacity > 0 and passenger_capacity <= 19),
  -- Route details
  departure_city         text        not null,
  departure_airport      text,
  destination_city       text        not null,
  destination_airport    text,
  departure_datetime     timestamptz not null,
  -- Pricing
  empty_leg_price        numeric(14, 2) not null
    check (empty_leg_price >= 0),
  price_currency         text        not null default 'INR'
    check (price_currency in ('INR', 'USD', 'EUR')),
  original_charter_price numeric(14, 2),
  -- Additional info
  notes                  text,
  booking_conditions     text,
  -- Approval workflow
  status                 text        not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'live')),
  reviewed_at            timestamptz,
  reviewed_by            uuid        references auth.users(id) on delete set null,
  review_notes           text,
  -- Audit
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  metadata               jsonb       not null default '{}'
);

comment on table public.operator_listing_submissions is
  'Operator-submitted empty-leg listings pending admin approval.';

create index if not exists operator_submissions_status_idx on public.operator_listing_submissions (status);
create index if not exists operator_submissions_email_idx on public.operator_listing_submissions (operator_email);
create index if not exists operator_submissions_created_idx on public.operator_listing_submissions (created_at desc);

-- ---------------------------------------------------------------------
-- 2. Updated-at trigger
-- ---------------------------------------------------------------------
drop trigger if exists trigger_operator_submissions_updated_at on public.operator_listing_submissions;
create trigger trigger_operator_submissions_updated_at
  before update on public.operator_listing_submissions
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------
-- 3. RLS Policies
-- ---------------------------------------------------------------------
alter table public.operator_listing_submissions enable row level security;

-- Anonymous users can INSERT (submit a listing) but not SELECT/UPDATE/DELETE
create policy anon_insert_operator_submission on public.operator_listing_submissions
  for insert to anon
  with check (true);

-- Authenticated staff can read all submissions
create policy staff_read_operator_submissions on public.operator_listing_submissions
  for select to authenticated
  using (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  );

-- Staff can update (approve/reject) submissions
create policy staff_update_operator_submissions on public.operator_listing_submissions
  for update to authenticated
  using (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  )
  with check (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  );

-- No SELECT for anonymous (privacy)
-- No DELETE for anyone by default

