-- Agent tables for EmptyLeg India 8-agent system
-- Applied to project mfijofonuggcxqlftgtl

CREATE TABLE IF NOT EXISTS public.agent_lead_prospects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name text NOT NULL,
  contact_person text,
  email text,
  phone text,
  whatsapp text,
  base_city text,
  fleet_estimate int,
  aircraft_types text[],
  source_url text,
  discovered_date timestamptz DEFAULT now(),
  status text DEFAULT 'discovered' CHECK (status IN ('discovered','contacted','interested','listed','not_interested')),
  quality_score int CHECK (quality_score BETWEEN 1 AND 5),
  metadata jsonb DEFAULT '{}'
);

CREATE INDEX IF NOT EXISTS idx_prospects_status ON public.agent_lead_prospects(status);
CREATE INDEX IF NOT EXISTS idx_prospects_city ON public.agent_lead_prospects(base_city);

CREATE TABLE IF NOT EXISTS public.agent_outreach_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prospect_id bigint REFERENCES public.agent_lead_prospects(id),
  channel text CHECK (channel IN ('email','whatsapp','call')),
  message_preview text,
  sent_at timestamptz DEFAULT now(),
  reply_received boolean DEFAULT false,
  reply_text text,
  status_change text
);

CREATE TABLE IF NOT EXISTS public.agent_customer_communications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id bigint REFERENCES public.booking_enquiries(id),
  channel text,
  message text,
  sent_by text DEFAULT 'agent_4',
  sent_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.agent_deal_summaries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id bigint REFERENCES public.booking_enquiries(id),
  offer_id bigint REFERENCES public.empty_leg_offers(id),
  customer_name text,
  operator_email text,
  quote_amount numeric,
  quote_currency text DEFAULT 'INR',
  offer_details text,
  deal_status text DEFAULT 'preparing' CHECK (deal_status IN ('preparing','awaiting_owner','approved_by_owner','confirmed','rejected','cancelled')),
  owner_approval_required boolean DEFAULT true,
  owner_approved_at timestamptz,
  owner_notes text,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_deals_owner_approval ON public.agent_deal_summaries(owner_approval_required, deal_status);

CREATE TABLE IF NOT EXISTS public.agent_whatsapp_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_type text CHECK (recipient_type IN ('waitlist','customer','operator')),
  recipient_id text,
  message_preview text,
  sent_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.agent_content_drafts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text,
  format text CHECK (format IN ('blog','instagram','linkedin','seo_page')),
  body text,
  keywords text[],
  status text DEFAULT 'draft' CHECK (status IN ('draft','review','published')),
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.agent_insights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week_start date NOT NULL,
  top_routes text[],
  enquiry_count int,
  deal_summary_count int,
  conversion_rate numeric,
  operator_response_rate numeric,
  recommendations text,
  created_at timestamptz DEFAULT now()
);

CREATE OR REPLACE VIEW public.agent_dashboard_view WITH (security_invoker = true) AS SELECT
  (SELECT count(*) FROM public.agent_lead_prospects) AS total_prospects,
  (SELECT count(*) FROM public.operator_listing_submissions WHERE status = 'pending') AS pending_submissions,
  (SELECT count(*) FROM public.empty_leg_offers WHERE availability_status = 'available') AS live_offers,
  (SELECT count(*) FROM public.booking_enquiries WHERE status = 'ENQUIRY_RECEIVED') AS new_enquiries,
  (SELECT count(*) FROM public.agent_deal_summaries WHERE deal_status = 'awaiting_owner' AND owner_approval_required = true) AS deals_awaiting_owner;
