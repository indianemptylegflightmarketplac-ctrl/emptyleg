-- OFFERS & OPERATORS POLICIES
-- =====================================================================

-- Public read: available, verified offers from authorized operators
create policy "public_read_available_offers" on public.empty_leg_offers
  for select to anon, authenticated
  using (
    availability_status = 'available'
    and offer_expires_at > now()
    and permission_status = 'verified'
    and exists (
      select 1 from public.operators op
      where op.id = empty_leg_offers.operator_id
        and op.authorization_status = 'authorized'
    )
  );

-- Public read: authorized operators
create policy "public_read_authorized_operators" on public.operators
  for select to anon, authenticated
  using (authorization_status = 'authorized');

-- Operators can read/update their own offers
create policy "operator_read_own_offers" on public.empty_leg_offers
  for select to authenticated
  using (
    operator_id in (
      select id from public.operators
      where contact_email = (select email from auth.users where id = auth.uid())
    )
  );

create policy "operator_update_own_offers" on public.empty_leg_offers
  for update to authenticated
  using (
    operator_id in (
      select id from public.operators
      where contact_email = (select email from auth.users where id = auth.uid())
    )
  )
  with check (
    operator_id in (
      select id from public.operators
      where contact_email = (select email from auth.users where id = auth.uid())
    )
  );

-- =====================================================================
-- ENQUIRY POLICIES (secure, final)
-- =====================================================================

-- 1. Authenticated INSERT: must use verified auth email
--    Anonymous users CANNOT insert directly via PostgREST.
--    All public enquiry submissions MUST go through the Edge Function
--    (POST /functions/v1/enquiries) which uses the service-role key
--    to call the atomic create_enquiry_atomic RPC.
create policy "auth_create_enquiries" on public.booking_enquiries
  for insert to authenticated
  with check (
    customer_email = (select email from auth.users where id = auth.uid())
  );

-- 2. Customer SELECT: own enquiries only (matched by verified email)
create policy "customer_read_own_enquiries" on public.booking_enquiries
  for select to authenticated
  using (
    customer_email = (select email from auth.users where id = auth.uid())
  );

-- 4. Staff SELECT: all enquiries (active staff with valid role)
create policy "staff_read_all_enquiries" on public.booking_enquiries
  for select to authenticated
  using (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  );

-- 5. Staff UPDATE: workflow state transitions (active staff with valid role)
create policy "staff_update_enquiries" on public.booking_enquiries
  for update to authenticated
  using (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  )
  with check (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  );

