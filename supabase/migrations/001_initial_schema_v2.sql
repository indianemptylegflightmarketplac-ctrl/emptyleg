-- ---------------------------------------------------------------------
-- 1. Operators (authorized suppliers)
-- ---------------------------------------------------------------------
create table if not exists public.operators (
  id              bigint generated by default as identity primary key,
  name            text        not null,
  contact_email   text        not null,
  contact_phone   text,
  authorization_status text   not null default 'pending'
    check (authorization_status in ('pending', 'authorized', 'suspended', 'rejected')),
  authorized_at   timestamptz,
  authorized_by   uuid        references auth.users(id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  metadata        jsonb       not null default '{}'
);

comment on table public.operators is
  'Authorized operators / suppliers who can submit empty-leg inventory.';

create index if not exists operators_status_idx on public.operators (authorization_status);

-- ---------------------------------------------------------------------
-- 2. Empty-leg offers (core inventory)
-- ---------------------------------------------------------------------
create table if not exists public.empty_leg_offers (
  id                     bigint generated by default as identity primary key,
  operator_id            bigint      not null references public.operators(id) on delete restrict,
  offer_reference        text        not null unique, -- operator's internal reference
  -- Route
  departure_city         text        not null,
  departure_airport      text,                       -- IATA code if available
  destination_city       text        not null,
  destination_airport    text,
  -- Timing
  departure_datetime     timestamptz not null,
  arrival_datetime       timestamptz,
  -- Aircraft
  aircraft_type          text        not null,       -- e.g., "Cessna Citation XLS+"
  aircraft_category      text        not null        -- e.g., "Light", "Midsize", "Heavy", "Turboprop"
    check (aircraft_category in ('Light', 'Midsize', 'Heavy', 'Turboprop', 'Ultra-Long Range')),
  passenger_capacity     integer     not null
    check (passenger_capacity > 0 and passenger_capacity <= 19),
  -- Pricing (whole-aircraft charter only in MVP)
  price_amount           numeric(14, 2) not null
    check (price_amount >= 0),
  price_currency         text        not null default 'INR'
    check (price_currency in ('INR', 'USD', 'EUR')),
  price_basis            text        not null default 'whole_aircraft'
    check (price_basis in ('whole_aircraft', 'per_seat')), -- per_seat only if permitted
  -- Conditions & restrictions
  booking_conditions     text,                       -- free text: cancellation, lead time, etc.
  baggage_allowance_kg   integer,
  pets_allowed           boolean     not null default false,
  wifi_available         boolean     not null default false,
  -- Inventory source & verification
  inventory_source       text        not null        -- 'operator_submitted', 'approved_feed', 'permitted_public'
    check (inventory_source in ('operator_submitted', 'approved_feed', 'permitted_public')),
  source_url             text,                       -- if from permitted public source
  source_retrieved_at    timestamptz,
  permission_status      text        not null default 'unverified'
    check (permission_status in ('unverified', 'verified', 'denied', 'expired')),
  last_verified_at       timestamptz,
  verified_by            uuid        references auth.users(id) on delete set null,
  -- Availability
  offer_expires_at       timestamptz not null,
  availability_status    text        not null default 'available'
    check (availability_status in ('available', 'pending_enquiry', 'under_quote', 'booked', 'expired', 'withdrawn')),
  -- Audit
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  created_by             uuid        references auth.users(id) on delete set null,
  metadata               jsonb       not null default '{}'
);

