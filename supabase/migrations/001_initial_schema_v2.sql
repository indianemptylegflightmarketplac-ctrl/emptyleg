-- 3. Booking enquiries (customer-facing)
-- ---------------------------------------------------------------------
create table if not exists public.booking_enquiries (
  id                     bigint generated by default as identity primary key,
  offer_id               bigint      not null references public.empty_leg_offers(id) on delete restrict,
  -- Customer details
  customer_name          text        not null,
  customer_email         text        not null,
  customer_phone         text        not null,
  customer_company       text,
  passenger_count        integer     not null
    check (passenger_count > 0 and passenger_count <= 19),
  -- Enquiry details
  special_requests       text,
  budget_max_amount      numeric(14, 2),
  budget_currency        text        default 'INR',
  -- Workflow state (ENQUIRY_RECEIVED -> OPERATOR_CHECK_PENDING -> QUOTE_READY -> ...)
  status                 text        not null default 'ENQUIRY_RECEIVED'
    check (status in (
      'ENQUIRY_RECEIVED',
      'OPERATOR_CHECK_PENDING',
      'QUOTE_READY',
      'CUSTOMER_APPROVAL_PENDING',
      'PAYMENT_PENDING',
      'OPERATOR_CONFIRMATION_PENDING',
      'CONFIRMED',
      'REJECTED',
      'EXPIRED',
      'CANCELLED',
      'PAYMENT_FAILED',
      'REFUND_PROCESSING',
      'REFUNDED'
    )),
  -- Operator response
  operator_quoted_price  numeric(14, 2),
  operator_quoted_currency text,
  operator_quote_expires_at timestamptz,
  operator_conditions    text,
  operator_responded_at  timestamptz,
  operator_responded_by  uuid        references auth.users(id) on delete set null,
  -- Customer approval
  customer_approved_at   timestamptz,
  customer_approved_by   uuid        references auth.users(id) on delete set null,
  -- Payment (test-mode only in MVP)
  payment_reference      text,
  payment_status         text        default 'not_required'
    check (payment_status in ('not_required', 'pending', 'verified', 'failed', 'refunded')),
  payment_verified_at    timestamptz,
  payment_verified_by    uuid        references auth.users(id) on delete set null,
  -- Final confirmation
  confirmed_at           timestamptz,
  confirmed_by           uuid        references auth.users(id) on delete set null,
  confirmation_reference text,
  -- Audit
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  metadata               jsonb       not null default '{}'
);

comment on table public.booking_enquiries is
  'Customer booking enquiries. State machine drives the workflow. No live payments in MVP.';

