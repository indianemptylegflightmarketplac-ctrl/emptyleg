-- ---------------------------------------------------------------------
-- 10. Atomic enquiry creation with offer validation (replaces Edge Function race condition)
--     This function is called by the Edge Function to atomically:
--     1. Lock the offer row (SELECT ... FOR UPDATE)
--     2. Validate offer exists, is available, not expired, capacity OK
--     3. Insert enquiry
--     4. Update offer status to 'pending_enquiry'
--     5. Insert workflow history
--     6. Return the new enquiry_id
-- ---------------------------------------------------------------------
create or replace function public.create_enquiry_atomic(
  p_offer_id bigint,
  p_customer_name text,
  p_customer_email text,
  p_customer_phone text,
  p_customer_company text,
  p_passenger_count integer,
  p_special_requests text,
  p_budget_max_amount numeric,
  p_budget_currency text
) returns bigint
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_offer public.empty_leg_offers%rowtype;
  v_enquiry_id bigint;
begin
  -- Lock the offer row for update to prevent concurrent bookings
  select * into v_offer
  from public.empty_leg_offers
  where id = p_offer_id
  for update;

  -- Validate offer exists
  if not found then
    raise exception 'Offer not found' using errcode = 'P0001';
  end if;

  -- Validate offer is available
  if v_offer.availability_status <> 'available' then
    raise exception 'Offer is no longer available' using errcode = 'P0002';
  end if;

  -- Validate offer not expired
  if v_offer.offer_expires_at < now() then
    raise exception 'Offer has expired' using errcode = 'P0003';
  end if;

  -- Validate passenger capacity
  if p_passenger_count > v_offer.passenger_capacity then
    raise exception 'Maximum passenger capacity is %', v_offer.passenger_capacity using errcode = 'P0004';
  end if;

  -- Insert enquiry
  insert into public.booking_enquiries (
    offer_id,
    customer_name,
    customer_email,
    customer_phone,
    customer_company,
    passenger_count,
    special_requests,
    budget_max_amount,
    budget_currency,
    status
  ) values (
    p_offer_id,
    p_customer_name,
    p_customer_email,
    p_customer_phone,
    p_customer_company,
    p_passenger_count,
    p_special_requests,
    p_budget_max_amount,
    p_budget_currency,
    'ENQUIRY_RECEIVED'
  ) returning id into v_enquiry_id;

  -- Update offer status
  update public.empty_leg_offers
  set availability_status = 'pending_enquiry',
      updated_at = now()
  where id = p_offer_id;

  -- Insert workflow history
  insert into public.booking_workflow_history (
    enquiry_id,
    from_status,
    to_status,
    actor_type,
    reason
  ) values (
    v_enquiry_id,
    null,
    'ENQUIRY_RECEIVED',
    'customer',
    'Enquiry submitted via marketplace'
  );

  return v_enquiry_id;
end;
$$;

