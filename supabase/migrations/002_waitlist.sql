-- ---------------------------------------------------------------------
-- 1. Waitlist table (public email capture from landing page)
-- ---------------------------------------------------------------------
create table if not exists public.waitlist (
  id              bigint generated by default as identity primary key,
  email           text        not null unique,
  source          text        not null default 'landing_page'
    check (source in ('landing_page', 'marketplace', 'operator_cta', 'other')),
  metadata        jsonb       not null default '{}',
  created_at      timestamptz not null default now()
);

comment on table public.waitlist is
  'Email waitlist signups from landing page and other public sources.';

create index if not exists waitlist_email_idx on public.waitlist (email);
create index if not exists waitlist_created_idx on public.waitlist (created_at desc);

-- ---------------------------------------------------------------------
-- 2. RLS Policies for Waitlist
-- ---------------------------------------------------------------------
alter table public.waitlist enable row level security;

-- Anonymous users can INSERT (signup) but not SELECT/UPDATE/DELETE
create policy anon_insert_waitlist on public.waitlist
  for insert to anon
  with check (true);

-- Authenticated users with staff role can read all waitlist entries
create policy staff_read_waitlist on public.waitlist
  for select to authenticated
  using (
    exists (
      select 1 from public.staff_profiles sp
      where sp.id = auth.uid()
        and sp.is_active
        and sp.role in ('admin', 'operator', 'support')
    )
  );

-- No policies for UPDATE/DELETE by default (denied for all)

